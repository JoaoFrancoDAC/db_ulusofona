SELECT
    ORDINAL_POSITION,
    COLUMN_NAME,
    DATA_TYPE,
    CHARACTER_MAXIMUM_LENGTH,
    NUMERIC_PRECISION,
    NUMERIC_SCALE,
    IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'HR'
  AND TABLE_NAME = 'EMPLOYEES'
ORDER BY ORDINAL_POSITION;

SELECT TOP (10)
    e.EMPLOYEE_ID,
    e.DEPARTMENT_ID,
    d.DEPARTMENT_NAME
FROM HR.EMPLOYEES AS e
INNER JOIN HR.DEPARTMENTS AS d
    ON e.DEPARTMENT_ID = d.DEPARTMENT_ID;

SELECT TOP (5)
    SALARY
FROM HR.EMPLOYEES
WHERE SALARY < 5000 OR SALARY > 10000;

SELECT
    EMPLOYEE_ID,
    FIRST_NAME,
    LAST_NAME,
    SALARY
FROM HR.EMPLOYEES
WHERE SALARY NOT BETWEEN 5000 AND 10000
ORDER BY SALARY ASC;

SELECT
    EMPLOYEE_ID,
    FIRST_NAME,
    HIRE_DATE
FROM HR.EMPLOYEES
WHERE HIRE_DATE NOT BETWEEN '2005-01-01' AND '2010-12-31';

SELECT
    EMPLOYEE_ID,
    SALARY * (COMMISSION_PCT+ 1) AS total_salary,
    COALESCE(COMMISSION_PCT, 0) AS commission_pct_value,
    COALESCE(COMMISSION_PCT, 0) * 2 AS commission_double,
    COALESCE(COMMISSION_PCT, 0) * 3 AS commission_triple
FROM HR.EMPLOYEES
ORDER BY commission_pct_value;



SELECT
    EMPLOYEE_ID,
    JOB_ID,
    CONCAT(
        FORMAT(EMPLOYEE_ID, '000000'),
        '-',
        JOB_ID
    ) AS formatted_identifier
FROM HR.EMPLOYEES
ORDER BY formatted_identifier;



